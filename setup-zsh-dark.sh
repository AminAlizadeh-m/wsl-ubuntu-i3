#!/usr/bin/env bash
# Set up zsh as your shell and give i3 a dark theme:
#   - zsh with autosuggestions, syntax highlighting and a git-aware prompt
#   - Alacritty terminal (dark), with a dark xterm as fallback
#   - dark i3 windows and bar, dark rofi launcher, dark GTK apps
#
# Safe to run more than once. Existing files are backed up the first time
# as <file>.pre-zsh-dark, and uninstall-i3.sh restores them.
# Usage: ./setup-zsh-dark.sh
set -euo pipefail

if [[ $EUID -eq 0 ]]; then
  echo "Run this as your normal user (it uses sudo where needed)." >&2
  exit 1
fi

I3_CFG="$HOME/.config/i3/config"
if [[ ! -f "$I3_CFG" ]]; then
  echo "No i3 config at $I3_CFG. Run ./install-i3.sh first." >&2
  exit 1
fi

# Back up a file once, before we first change it. Files this script wrote
# itself (they contain the marker) are not "originals", so skip those.
backup_once() {
  [[ -e "$1" && ! -e "$1.pre-zsh-dark" ]] || return 0
  grep -q 'setup-zsh-dark.sh\|wsl-dark-theme' "$1" 2>/dev/null && return 0
  cp -a "$1" "$1.pre-zsh-dark"
}

# ---------------------------------------------------------------- packages
echo "==> Installing zsh, plugins and terminals"
sudo apt-get update
sudo DEBIAN_FRONTEND=noninteractive apt-get install -y \
  zsh zsh-autosuggestions zsh-syntax-highlighting alacritty xterm x11-xserver-utils

# Nice to have; skip any that this Ubuntu release doesn't have.
for pkg in fonts-jetbrains-mono gnome-themes-extra; do
  if apt-cache show "$pkg" >/dev/null 2>&1; then
    sudo DEBIAN_FRONTEND=noninteractive apt-get install -y "$pkg"
  else
    echo "    (skipping $pkg: not available)"
  fi
done

if fc-list 2>/dev/null | grep -qi "JetBrains Mono"; then
  FONT="JetBrains Mono"
else
  FONT="DejaVu Sans Mono"
fi

# Colours used everywhere below
BG="#1e1e2e"; BG_ALT="#2a2a3c"; FG="#d4d4e0"; MUTED="#6c6c80"
BLUE="#7aa2f7"; RED="#f7768e"; GREEN="#9ece6a"; YELLOW="#e0af68"
MAGENTA="#bb9af7"; CYAN="#7dcfff"

# ---------------------------------------------------------------- zsh
ZSHRC="$HOME/.zshrc"
backup_once "$ZSHRC"
echo "==> Writing $ZSHRC"
cat > "$ZSHRC" <<'ZSH'
# Generated by setup-zsh-dark.sh (wsl-ubuntu-i3). Edit freely.

# History
HISTFILE=~/.zsh_history
HISTSIZE=50000
SAVEHIST=50000
setopt share_history hist_ignore_dups hist_ignore_space extended_history

# Completion
autoload -Uz compinit && compinit
zstyle ':completion:*' menu select
zstyle ':completion:*' matcher-list 'm:{a-z}={A-Z}'
zstyle ':completion:*' list-colors "${(s.:.)LS_COLORS}"

# Keys: emacs-style, Up/Down search history by what you've typed
bindkey -e
autoload -Uz up-line-or-beginning-search down-line-or-beginning-search
zle -N up-line-or-beginning-search
zle -N down-line-or-beginning-search
bindkey '^[[A' up-line-or-beginning-search
bindkey '^[[B' down-line-or-beginning-search
bindkey '^[[H' beginning-of-line
bindkey '^[[F' end-of-line
bindkey '^[[3~' delete-char

setopt autocd interactive_comments

# Prompt: ~/path (git-branch) ❯   (arrow turns red after a failed command)
autoload -Uz vcs_info
precmd() { vcs_info }
zstyle ':vcs_info:git:*' formats ' %F{magenta}(%b)%f'
setopt prompt_subst
PROMPT='%F{blue}%~%f${vcs_info_msg_0_} %(?.%F{green}.%F{red})❯%f '

# Colours and aliases
eval "$(dircolors -b)"
alias ls='ls --color=auto'
alias ll='ls -lah'
alias grep='grep --color=auto'

# Plugins (from apt). Syntax highlighting must be loaded last.
[[ -r /usr/share/zsh-autosuggestions/zsh-autosuggestions.zsh ]] &&
  source /usr/share/zsh-autosuggestions/zsh-autosuggestions.zsh
ZSH_AUTOSUGGEST_HIGHLIGHT_STYLE='fg=#6c6c80'
[[ -r /usr/share/zsh-syntax-highlighting/zsh-syntax-highlighting.zsh ]] &&
  source /usr/share/zsh-syntax-highlighting/zsh-syntax-highlighting.zsh
ZSH

# ---------------------------------------------------------------- alacritty
AL_CFG="$HOME/.config/alacritty/alacritty.toml"
mkdir -p "$(dirname "$AL_CFG")"
backup_once "$AL_CFG"
echo "==> Writing $AL_CFG"
cat > "$AL_CFG" <<EOF
# Generated by setup-zsh-dark.sh (wsl-ubuntu-i3)
[window]
padding = { x = 8, y = 6 }

[font]
size = 11.0
normal = { family = "$FONT" }

[colors.primary]
background = "$BG"
foreground = "$FG"

[colors.cursor]
text = "$BG"
cursor = "$BLUE"

[colors.selection]
text = "$FG"
background = "#3b3b55"

[colors.normal]
black = "#2a2a3c"
red = "$RED"
green = "$GREEN"
yellow = "$YELLOW"
blue = "$BLUE"
magenta = "$MAGENTA"
cyan = "$CYAN"
white = "#c0c0d0"

[colors.bright]
black = "$MUTED"
red = "#ff8fa3"
green = "#b4e88a"
yellow = "#f0c38a"
blue = "#9bb8ff"
magenta = "#cfb4ff"
cyan = "#a0e0ff"
white = "#ffffff"
EOF

# ---------------------------------------------------------------- xterm (fallback)
XRES="$HOME/.Xresources"
backup_once "$XRES"
# Replace our previous block, keep anything else in the file
if [[ -f "$XRES" ]]; then
  sed -i '/^! >>> wsl-dark-theme >>>/,/^! <<< wsl-dark-theme <<</d' "$XRES"
fi
echo "==> Adding dark xterm colours to $XRES"
cat >> "$XRES" <<EOF
! >>> wsl-dark-theme >>>
XTerm*faceName: $FONT
XTerm*faceSize: 11
XTerm*termName: xterm-256color
XTerm*metaSendsEscape: true
XTerm*background: $BG
XTerm*foreground: $FG
XTerm*cursorColor: $BLUE
XTerm*color0: #2a2a3c
XTerm*color1: $RED
XTerm*color2: $GREEN
XTerm*color3: $YELLOW
XTerm*color4: $BLUE
XTerm*color5: $MAGENTA
XTerm*color6: $CYAN
XTerm*color7: #c0c0d0
XTerm*color8: $MUTED
XTerm*color9: #ff8fa3
XTerm*color10: #b4e88a
XTerm*color11: #f0c38a
XTerm*color12: #9bb8ff
XTerm*color13: #cfb4ff
XTerm*color14: #a0e0ff
XTerm*color15: #ffffff
! <<< wsl-dark-theme <<<
EOF

# ---------------------------------------------------------------- terminal wrapper
# Xephyr and xrdp have no GPU, so run Alacritty with software rendering, and
# open xterm instead if Alacritty fails to start.
TERM_WRAPPER="$HOME/.local/bin/i3-term"
mkdir -p "$(dirname "$TERM_WRAPPER")"
echo "==> Writing $TERM_WRAPPER"
cat > "$TERM_WRAPPER" <<'EOF'
#!/bin/sh
# Terminal launcher for i3 (from setup-zsh-dark.sh)
export LIBGL_ALWAYS_SOFTWARE=1
if command -v alacritty >/dev/null 2>&1; then
  start=$(date +%s)
  alacritty "$@" && exit 0
  # Only fall back if Alacritty died right away (failed to start)
  [ $(( $(date +%s) - start )) -ge 3 ] && exit 0
fi
exec xterm "$@"
EOF
chmod +x "$TERM_WRAPPER"

# ---------------------------------------------------------------- rofi
ROFI_CFG="$HOME/.config/rofi/config.rasi"
mkdir -p "$(dirname "$ROFI_CFG")"
backup_once "$ROFI_CFG"
echo "==> Writing $ROFI_CFG"
cat > "$ROFI_CFG" <<EOF
/* Generated by setup-zsh-dark.sh (wsl-ubuntu-i3) */
configuration {
  show-icons: false;
  font: "$FONT 11";
}
* {
  background-color: $BG;
  text-color: $FG;
  border-color: $BLUE;
}
window { width: 40%; border: 2px; padding: 12px; }
inputbar { padding: 6px; children: [prompt, entry]; }
prompt { text-color: $BLUE; padding: 0 8px 0 0; }
listview { lines: 10; padding: 8px 0 0 0; }
element { padding: 4px 8px; }
element selected { background-color: $BG_ALT; text-color: $BLUE; }
element-text { background-color: inherit; text-color: inherit; }
EOF

# ---------------------------------------------------------------- GTK apps
for v in 3.0 4.0; do
  GTK_CFG="$HOME/.config/gtk-$v/settings.ini"
  if [[ ! -f "$GTK_CFG" ]]; then
    mkdir -p "$(dirname "$GTK_CFG")"
    printf '[Settings]\ngtk-application-prefer-dark-theme=1\n' > "$GTK_CFG"
    [[ $v == 3.0 ]] && echo 'gtk-theme-name=Adwaita-dark' >> "$GTK_CFG"
    echo "==> Wrote $GTK_CFG"
  elif ! grep -q 'gtk-application-prefer-dark-theme' "$GTK_CFG"; then
    echo "    $GTK_CFG exists; add 'gtk-application-prefer-dark-theme=1' under [Settings] for dark GTK apps"
  fi
done

# ---------------------------------------------------------------- i3
echo "==> Updating $I3_CFG"
backup_once "$I3_CFG"
TMP_CFG="$(mktemp)"

# 1. drop our previous block, 2. point Alt+Enter at the wrapper (replace, don't
# duplicate), 3. comment out the stock bar so there's only one bar.
awk -v term="$TERM_WRAPPER" '
  /^# >>> wsl-dark-theme >>>/ { skip = 1; next }
  /^# <<< wsl-dark-theme <<</ { skip = 0; next }
  skip { next }
  /^bindsym \$mod\+Return exec/ { print "bindsym $mod+Return exec --no-startup-id " term; next }
  /^bar[ \t]*\{/ { inbar = 1 }
  inbar { print "#" $0; if ($0 ~ /^\}/) inbar = 0; next }
  { print }
' "$I3_CFG" > "$TMP_CFG"

cat >> "$TMP_CFG" <<EOF
# >>> wsl-dark-theme >>>
# Added by setup-zsh-dark.sh. Re-running the script replaces this block.
font pango:$FONT 10
exec_always --no-startup-id xrdb -merge ~/.Xresources
exec --no-startup-id xsetroot -solid "$BG"

# class                 border    backgr.   text      indicator child_border
client.focused          $BLUE     $BLUE     $BG       $MAGENTA  $BLUE
client.focused_inactive $BG_ALT   $BG_ALT   $FG       $BG_ALT   $BG_ALT
client.unfocused        $BG       $BG       $MUTED    $BG       $BG
client.urgent           $RED      $RED      $BG       $RED      $RED
client.background       $BG

default_border pixel 2
gaps inner 6

bar {
    status_command i3status
    position top
    font pango:$FONT 10
    colors {
        background $BG
        statusline $FG
        separator  $MUTED
        #                  border    backgr.   text
        focused_workspace  $BLUE     $BLUE     $BG
        active_workspace   $BG_ALT   $BG_ALT   $FG
        inactive_workspace $BG       $BG       $MUTED
        urgent_workspace   $RED      $RED      $BG
    }
}
# <<< wsl-dark-theme <<<
EOF

if command -v i3 >/dev/null && ! i3 -C -c "$TMP_CFG" >/dev/null 2>&1; then
  echo "The new i3 config has errors, keeping your old one. Details:" >&2
  i3 -C -c "$TMP_CFG" >&2 || true
  rm -f "$TMP_CFG"
  exit 1
fi
cat "$TMP_CFG" > "$I3_CFG"   # keep the file's permissions
rm -f "$TMP_CFG"

# ---------------------------------------------------------------- login shell
ZSH_PATH="$(command -v zsh)"
CURRENT_SHELL="$(getent passwd "$USER" | cut -d: -f7)"
if [[ "$CURRENT_SHELL" != "$ZSH_PATH" ]]; then
  echo "==> Making zsh your login shell (enter your Linux password if asked)"
  echo "    This also changes the shell that Windows Terminal's Ubuntu tab and 'wsl' open."
  if ! chsh -s "$ZSH_PATH"; then
    echo "    chsh failed. Run 'chsh -s $ZSH_PATH' yourself later." >&2
  fi
fi

echo
echo "Done."
echo "  - In i3, press Alt+Shift+r to load the dark theme."
echo "  - Alt+Enter opens Alacritty with zsh (new terminals only)."
echo "  - Close and reopen Ubuntu / Windows Terminal to use zsh there too."
echo "  - Backups of replaced files end in .pre-zsh-dark"
