#!/usr/bin/env bash
# Make i3 look less basic:
#   - polybar instead of i3bar (workspaces, window title, CPU, RAM, disk, clock)
#   - autotiling: new windows alternate between side-by-side and stacked splits
#   - picom: shadows, fading and rounded corners (skip with --no-picom)
#   - optional wallpaper: put an image at ~/.wallpaper
# Colours follow your theme; switch with ./set-theme.sh <theme>.
#
# Usage: ./setup-polybar.sh [--no-picom]
set -euo pipefail

if [[ $EUID -eq 0 ]]; then
  echo "Run this as your normal user (it uses sudo where needed)." >&2
  exit 1
fi

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
I3_CFG="$HOME/.config/i3/config"
if [[ ! -f "$I3_CFG" ]]; then
  echo "No i3 config at $I3_CFG. Run ./install-i3.sh first." >&2
  exit 1
fi

USE_PICOM=1
[[ "${1:-}" == "--no-picom" ]] && USE_PICOM=0

# ---------------------------------------------------------------- packages
PKGS=(polybar autotiling feh)
[[ $USE_PICOM -eq 1 ]] && PKGS+=(picom)
echo "==> Installing ${PKGS[*]}"
sudo apt-get update
sudo DEBIAN_FRONTEND=noninteractive apt-get install -y "${PKGS[@]}"

# ---------------------------------------------------------------- launcher
# i3 runs this on every start/restart. It keeps a list of what it started per
# display, so restarting one i3 (e.g. the Xephyr window) doesn't touch the bar
# of another (e.g. an RDP session).
LAUNCHER="$HOME/.local/bin/i3-extras"
mkdir -p "$(dirname "$LAUNCHER")"
echo "==> Writing $LAUNCHER"
cat > "$LAUNCHER" <<'EOF'
#!/bin/sh
# Start polybar and autotiling for this i3 session (from setup-polybar.sh).
run_dir="${XDG_RUNTIME_DIR:-/tmp}"
pidfile="$run_dir/wsl-i3-extras$(printf '%s' "$DISPLAY" | tr -c 'A-Za-z0-9' '_').pids"
if [ -f "$pidfile" ]; then
  while read -r pid; do kill "$pid" 2>/dev/null; done < "$pidfile"
fi
: > "$pidfile"
polybar main >/dev/null 2>&1 &
echo $! >> "$pidfile"
if command -v autotiling >/dev/null 2>&1; then
  autotiling >/dev/null 2>&1 &
  echo $! >> "$pidfile"
fi
# picom: only one compositor per display can run. Something else may already
# have started one (e.g. the stock i3 config's "dex --autostart" runs picom's
# autostart entry), so wait a moment and only start it if none is running here.
if [ -f "$HOME/.config/picom/.wsl-picom" ] && command -v picom >/dev/null 2>&1; then
  (
    sleep 2
    for pid in $(pgrep -u "$(id -u)" -x picom); do
      tr '\0' '\n' < "/proc/$pid/environ" 2>/dev/null | grep -qx "DISPLAY=$DISPLAY" && exit 0
    done
    exec picom --config "$HOME/.config/picom/picom.conf" >/dev/null 2>&1
  ) &
fi
# Wallpaper (after the theme has set the plain background colour)
if [ -f "$HOME/.wallpaper" ]; then
  (sleep 1; feh --no-fehbg --bg-fill "$HOME/.wallpaper") &
fi
EOF
chmod +x "$LAUNCHER"

# ---------------------------------------------------------------- picom
rm -f "$HOME/.config/picom/.wsl-picom"
if [[ $USE_PICOM -eq 1 ]]; then
  PICOM_CFG="$HOME/.config/picom/picom.conf"
  mkdir -p "$(dirname "$PICOM_CFG")"
  [[ -f "$PICOM_CFG" && ! -f "$PICOM_CFG.pre-zsh-dark" ]] && ! grep -q 'setup-polybar.sh' "$PICOM_CFG" &&
    cp -a "$PICOM_CFG" "$PICOM_CFG.pre-zsh-dark"
  echo "==> Writing $PICOM_CFG"
  cat > "$PICOM_CFG" <<'EOF'
# Generated by setup-polybar.sh (wsl-ubuntu-i3)
# The i3 window and RDP have no GPU, so use the CPU (xrender) backend and keep
# effects light. If windows feel slow or turn black, run: pkill picom
backend = "xrender";
vsync = false;

shadow = true;
shadow-radius = 10;
shadow-opacity = 0.35;
shadow-offset-x = -8;
shadow-offset-y = -8;
shadow-exclude = [ "class_g = 'Polybar'" ];

fading = true;
fade-in-step = 0.08;
fade-out-step = 0.08;

corner-radius = 6;
rounded-corners-exclude = [ "class_g = 'Polybar'" ];
EOF
fi

[[ $USE_PICOM -eq 1 ]] && touch "$HOME/.config/picom/.wsl-picom"

# ---------------------------------------------------------------- i3
echo "==> Updating $I3_CFG"
[[ ! -e "$I3_CFG.pre-zsh-dark" ]] && ! grep -q 'wsl-dark-theme' "$I3_CFG" && cp -a "$I3_CFG" "$I3_CFG.pre-zsh-dark"
TMP_CFG="$(mktemp)"
sed '/^# >>> wsl-polybar >>>/,/^# <<< wsl-polybar <<</d' "$I3_CFG" > "$TMP_CFG"
{
  echo "# >>> wsl-polybar >>>"
  echo "# Added by setup-polybar.sh. Re-running it replaces this block."
  echo "exec_always --no-startup-id $LAUNCHER"
  echo "# <<< wsl-polybar <<<"
} >> "$TMP_CFG"
if command -v i3 >/dev/null && ! i3 -C -c "$TMP_CFG" >/dev/null 2>&1; then
  echo "The new i3 config has errors, keeping your old one. Details:" >&2
  i3 -C -c "$TMP_CFG" >&2 || true
  rm -f "$TMP_CFG"
  exit 1
fi
cat "$TMP_CFG" > "$I3_CFG"
rm -f "$TMP_CFG"

# ---------------------------------------------------------------- colours
# The flag tells set-theme.sh to write polybar's config and hide i3bar.
mkdir -p "$HOME/.config/polybar"
touch "$HOME/.config/polybar/.wsl-polybar"
THEME="$(sed -n 's/^# theme: //p' "$I3_CFG" | head -1)"
"$DIR/set-theme.sh" "${THEME:-tokyonight}"

echo
echo "Done. polybar, autotiling$([[ $USE_PICOM -eq 1 ]] && echo ', picom') are set up."
echo "  - Press Alt+Shift+r in i3 to start them."
echo "  - Wallpaper: copy an image to ~/.wallpaper, then press Alt+Shift+r."
[[ $USE_PICOM -eq 1 ]] && echo "  - If windows feel slow or go black: pkill picom (or re-run with --no-picom)."
exit 0
