#!/usr/bin/env bash
# Install GlazeWM on Windows (an i3-style tiling window manager for Windows)
# and give it a config with the same Alt shortcuts as i3 here, in the colours
# of your current theme. Run it from WSL; it uses winget and cmd.exe.
#
# GlazeWM tiles every window, including Linux apps opened through WSLg.
# Note: its Alt shortcuts are grabbed by Windows, so they also fire while you
# use i3 in the Xephyr window or over RDP. Press Alt+Shift+P to pause GlazeWM
# while you use i3, and again to resume.
#
# Usage: ./setup-glazewm.sh            install GlazeWM and write the config
#        ./setup-glazewm.sh --config   only (re)write the config, e.g. after set-theme.sh
set -euo pipefail

ONLY_CONFIG=0
[[ "${1:-}" == "--config" ]] && ONLY_CONFIG=1

# ---------------------------------------------------------------- Windows home
if ! command -v cmd.exe >/dev/null 2>&1; then
  echo "Can't run Windows programs from WSL (cmd.exe not found)." >&2
  echo "Windows interop may be turned off in /etc/wsl.conf ([interop] enabled=false)." >&2
  exit 1
fi
# Run cmd.exe from a Windows folder, otherwise it warns about UNC paths.
WIN_PROFILE="$(cd /mnt/c 2>/dev/null; cmd.exe /c 'echo %USERPROFILE%' 2>/dev/null | tr -d '\r')"
if [[ -z "$WIN_PROFILE" || "$WIN_PROFILE" == "%USERPROFILE%" ]]; then
  echo "Could not find your Windows user folder." >&2
  exit 1
fi
WIN_HOME="$(wslpath "$WIN_PROFILE")"
CFG_DIR="$WIN_HOME/.glzr/glazewm"
CFG="$CFG_DIR/config.yaml"

# ---------------------------------------------------------------- install
if [[ $ONLY_CONFIG -eq 0 ]]; then
  echo "==> Installing GlazeWM with winget (Windows may ask for permission)"
  WINGET_OPTS=(--accept-package-agreements --accept-source-agreements)
  if ! (cd /mnt/c 2>/dev/null; { winget.exe install --exact --id glzr-io.glazewm "${WINGET_OPTS[@]}" ||
                       winget.exe install GlazeWM "${WINGET_OPTS[@]}"; }); then
    echo "    winget did not finish the install (it may already be installed)."
    echo "    If GlazeWM isn't installed, run this in PowerShell:  winget install GlazeWM"
  fi
fi

# ---------------------------------------------------------------- colours
# Take the border colours from the i3 theme (set-theme.sh), if there is one.
I3_CFG="$HOME/.config/i3/config"
FOCUSED="#7aa2f7"; OTHER="#292e42"
if [[ -f "$I3_CFG" ]]; then
  f=$(awk '/^client\.focused[ \t]/ {print $2; exit}' "$I3_CFG")
  o=$(awk '/^client\.focused_inactive[ \t]/ {print $2; exit}' "$I3_CFG")
  [[ "$f" =~ ^#[0-9a-fA-F]{6}$ ]] && FOCUSED="$f"
  [[ "$o" =~ ^#[0-9a-fA-F]{6}$ ]] && OTHER="$o"
fi

# ---------------------------------------------------------------- config
mkdir -p "$CFG_DIR"
if [[ -f "$CFG" && ! -f "$CFG.pre-wsl-i3" ]] && ! grep -q 'setup-glazewm.sh' "$CFG"; then
  cp "$CFG" "$CFG.pre-wsl-i3"
  echo "==> Backed up your existing GlazeWM config to $CFG.pre-wsl-i3"
fi

echo "==> Writing $CFG"
cat > "$CFG" <<EOF
# Generated by setup-glazewm.sh (wsl-ubuntu-i3). Re-running it overwrites this file.
# Shortcuts follow the i3 setup in WSL: Alt is the modifier.
# Delete this file and restart GlazeWM to get GlazeWM's default config back.

general:
  startup_commands: []
  shutdown_commands: []
  config_reload_commands: []
  focus_follows_cursor: false
  toggle_workspace_on_refocus: false
  cursor_jump:
    enabled: true
    trigger: 'monitor_focus'
  hide_method: 'cloak'
  show_all_in_taskbar: false

gaps:
  scale_with_dpi: true
  inner_gap: '8px'
  outer_gap:
    top: '8px'
    right: '8px'
    bottom: '8px'
    left: '8px'

window_effects:
  focused_window:
    border:
      enabled: true
      color: '$FOCUSED'
    hide_title_bar:
      enabled: false
    corner_style:
      enabled: false
      style: 'square'
    transparency:
      enabled: false
      opacity: '90%'
  other_windows:
    border:
      enabled: true
      color: '$OTHER'
    hide_title_bar:
      enabled: false
    corner_style:
      enabled: false
      style: 'square'
    transparency:
      enabled: false
      opacity: '90%'

window_behavior:
  initial_state: 'tiling'
  state_defaults:
    floating:
      centered: true
      shown_on_top: false
    fullscreen:
      maximized: false
      shown_on_top: false

workspaces:
  - name: '1'
  - name: '2'
  - name: '3'
  - name: '4'
  - name: '5'
  - name: '6'
  - name: '7'
  - name: '8'
  - name: '9'

window_rules:
  - commands: ['ignore']
    match:
      # The i3 window (Xephyr) and Remote Desktop: leave them alone
      - window_title: { regex: '^i3 \(WSL\)' }
      - window_process: { equals: 'mstsc' }
      # Picture-in-picture video
      - window_title: { regex: '[Pp]icture.in.[Pp]icture' }
        window_class: { regex: 'Chrome_WidgetWin_1|MozillaDialogClass' }
      # PowerToys popups
      - window_process: { equals: 'PowerToys' }
        window_class: { regex: 'HwndWrapper\[PowerToys\.PowerAccent.*?\]' }

binding_modes:
  # Alt+R, then h/j/k/l or arrows to resize; Escape or Enter to finish
  - name: 'resize'
    keybindings:
      - commands: ['resize --width -2%']
        bindings: ['h', 'left']
      - commands: ['resize --width +2%']
        bindings: ['l', 'right']
      - commands: ['resize --height +2%']
        bindings: ['k', 'up']
      - commands: ['resize --height -2%']
        bindings: ['j', 'down']
      - commands: ['wm-disable-binding-mode --name resize']
        bindings: ['escape', 'enter']

keybindings:
  # Focus and move windows
  - commands: ['focus --direction left']
    bindings: ['alt+h', 'alt+left']
  - commands: ['focus --direction right']
    bindings: ['alt+l', 'alt+right']
  - commands: ['focus --direction up']
    bindings: ['alt+k', 'alt+up']
  - commands: ['focus --direction down']
    bindings: ['alt+j', 'alt+down']
  - commands: ['move --direction left']
    bindings: ['alt+shift+h', 'alt+shift+left']
  - commands: ['move --direction right']
    bindings: ['alt+shift+l', 'alt+shift+right']
  - commands: ['move --direction up']
    bindings: ['alt+shift+k', 'alt+shift+up']
  - commands: ['move --direction down']
    bindings: ['alt+shift+j', 'alt+shift+down']

  # Layout
  - commands: ['wm-enable-binding-mode --name resize']
    bindings: ['alt+r']
  - commands: ['toggle-tiling-direction']
    bindings: ['alt+v']
  - commands: ['toggle-floating --centered']
    bindings: ['alt+shift+space']
  - commands: ['wm-cycle-focus']
    bindings: ['alt+space']
  - commands: ['toggle-fullscreen']
    bindings: ['alt+f']
  - commands: ['toggle-minimized']
    bindings: ['alt+m']

  # Windows and GlazeWM itself
  - commands: ['close']
    bindings: ['alt+shift+q']
  - commands: ['wm-toggle-pause']
    bindings: ['alt+shift+p']
  - commands: ['wm-reload-config']
    bindings: ['alt+shift+r']
  - commands: ['wm-redraw']
    bindings: ['alt+shift+w']
  - commands: ['wm-exit']
    bindings: ['alt+shift+e']

  # Alt+Enter: Windows Terminal with your WSL shell in your Linux home
  - commands: ['shell-exec wt.exe wsl.exe ~']
    bindings: ['alt+enter']

  # Workspaces
  - commands: ['focus --workspace 1']
    bindings: ['alt+1']
  - commands: ['focus --workspace 2']
    bindings: ['alt+2']
  - commands: ['focus --workspace 3']
    bindings: ['alt+3']
  - commands: ['focus --workspace 4']
    bindings: ['alt+4']
  - commands: ['focus --workspace 5']
    bindings: ['alt+5']
  - commands: ['focus --workspace 6']
    bindings: ['alt+6']
  - commands: ['focus --workspace 7']
    bindings: ['alt+7']
  - commands: ['focus --workspace 8']
    bindings: ['alt+8']
  - commands: ['focus --workspace 9']
    bindings: ['alt+9']
  - commands: ['move --workspace 1', 'focus --workspace 1']
    bindings: ['alt+shift+1']
  - commands: ['move --workspace 2', 'focus --workspace 2']
    bindings: ['alt+shift+2']
  - commands: ['move --workspace 3', 'focus --workspace 3']
    bindings: ['alt+shift+3']
  - commands: ['move --workspace 4', 'focus --workspace 4']
    bindings: ['alt+shift+4']
  - commands: ['move --workspace 5', 'focus --workspace 5']
    bindings: ['alt+shift+5']
  - commands: ['move --workspace 6', 'focus --workspace 6']
    bindings: ['alt+shift+6']
  - commands: ['move --workspace 7', 'focus --workspace 7']
    bindings: ['alt+shift+7']
  - commands: ['move --workspace 8', 'focus --workspace 8']
    bindings: ['alt+shift+8']
  - commands: ['move --workspace 9', 'focus --workspace 9']
    bindings: ['alt+shift+9']
EOF

echo
echo "Done."
echo "  - Start GlazeWM from the Start menu (or press Alt+Shift+R if it's already running)."
echo "  - Alt+Enter opens Windows Terminal with WSL; Alt+arrows move focus; Alt+1..9 switch workspace."
echo "  - Press Alt+Shift+P to pause GlazeWM while you use i3, and again to resume."
echo "  - Re-run with --config after set-theme.sh to update the border colours."
